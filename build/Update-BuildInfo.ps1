[CmdletBinding()]
param([Parameter(Mandatory)][string]$OutputFile)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$rawVersion = [Environment]::GetEnvironmentVariable('GPUSUITE_PUBLIC_VERSION')

if ([string]::IsNullOrWhiteSpace($rawVersion)) {
    try {
        $tag = & git -C $root describe --tags --abbrev=0 --match 'v[0-9]*' 2>$null
        if ($LASTEXITCODE -eq 0 -and -not [string]::IsNullOrWhiteSpace($tag)) { $rawVersion = $tag.Trim() }
    } catch { }
}
if ([string]::IsNullOrWhiteSpace($rawVersion)) { $rawVersion = '0.1.0-public' }

$displayVersion = $rawVersion.Trim() -replace '^v', ''
$numericVersion = $displayVersion -replace '-public$', ''
$parsedVersion = $null
if (-not [Version]::TryParse($numericVersion, [ref]$parsedVersion) -or $parsedVersion.Build -lt 0) {
    throw "Invalid public version '$rawVersion'. Expected vMAJOR.MINOR.PATCH, MAJOR.MINOR.PATCH, or MAJOR.MINOR.PATCH-public."
}

$revision = if ($parsedVersion.Revision -ge 0) { $parsedVersion.Revision } else { 0 }
$assemblyVersion = "$($parsedVersion.Major).$($parsedVersion.Minor).$($parsedVersion.Build).$revision"
$commit = [Environment]::GetEnvironmentVariable('GITHUB_SHA')
if ([string]::IsNullOrWhiteSpace($commit)) {
    try {
        $gitCommit = & git -C $root rev-parse --short HEAD 2>$null
        if ($LASTEXITCODE -eq 0 -and -not [string]::IsNullOrWhiteSpace($gitCommit)) { $commit = $gitCommit.Trim() }
    } catch { }
}
if ([string]::IsNullOrWhiteSpace($commit)) { $commit = 'public-main' }
$timestamp = [DateTime]::UtcNow.ToString('yyyy-MM-dd HH:mm:ssZ')
$informationalVersion = "$displayVersion+$commit"

$content = @"
// <auto-generated />
using System.Reflection;

[assembly: AssemblyVersion("$assemblyVersion")]
[assembly: AssemblyFileVersion("$assemblyVersion")]
[assembly: AssemblyInformationalVersion("$informationalVersion")]

namespace GpuSuite;
internal static class BuildInfo
{
    public const string ProductName = "Hardware Busters GPU Test Suite";
    public const string Version = "$displayVersion";
    public const int Revision = $revision;
    public const string BuildTimestamp = "$timestamp";
    public const string CommitHash = "$commit";
    public const string DisplayVersion = "Hardware Busters GPU Test Suite v$displayVersion";
    public const string InformationalVersion = "$informationalVersion";
}
"@

New-Item -ItemType Directory -Force -Path (Split-Path -Parent $OutputFile) | Out-Null
[IO.File]::WriteAllText($OutputFile, $content, [Text.UTF8Encoding]::new($false))
